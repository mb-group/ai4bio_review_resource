/* Merges the 67 "concepts" (site-data.js) into the Glossary of resource.html.
   Writes (1) the CX block into resource.html between markers, (2) glossary-map.js (concept id -> glossary slug).
   Run from the repo root:  node build/merge_glossary.js   (idempotent) */
const fs=require('fs');
const slug=t=>t.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const w={};new Function('window',fs.readFileSync('site-data.js','utf8')+';window.T=TERMS;window.E=EXAMPLES')(w);
const T=w.T,E=w.E;
let html=fs.readFileSync('resource.html','utf8');
const G=JSON.parse(html.match(/const GLOSS = (\[.*\]);\n/)[1]);   // original S1 rows only (extras pushed at runtime)
const gnames=new Set(G.map(g=>g.t));
/* concept id -> existing S1 glossary term */
const MAP={
 'biological-foundation-model':'Foundation model','agentic-system':'Agent / agentic system','knowledge-boundary':'Knowledge boundary',
 'embedding':'Embedding','llm':'Large language model (LLM)','self-supervised-learning':'Self-supervised learning','probing':'Probing',
 'fine-tuning':'Fine-tuning','zero-shot-prediction':'Zero-shot prediction','vocabulary':'Vocabulary and token','token':'Vocabulary and token',
 'grammar':'Grammar','corpus':'Corpus','sparse-autoencoder':'Sparse autoencoder','five-design-elements':'Five design elements',
 'generalization':'Generalization','transformer':'Transformer','inductive-bias':'Inductive bias','masked-language-modeling':'Masked language modeling',
 'autoregressive-modeling':'Autoregressive training','contrastive-learning':'Contrastive and metric learning',
 'intrinsic-vs-downstream-evaluation':'Intrinsic and downstream evaluation','transfer-learning':'Transfer learning',
 'in-silico-perturbation':'In silico perturbation','interpretability-analysis':'Interpretability analysis','inputs-vs-outputs':'Inputs and outputs',
 'graph-neural-network':'Graph neural network','representation-model':'Representation model','predictive-model':'Predictive model',
 'generative-model':'Generative model','perturbation-model':'Virtual cell / perturbation model','hallucination':'Hallucination',
 'rag':'Retrieval-augmented generation (RAG)','function-calling':'Tool use (function calling)','reasoning-model':'Reasoning model',
 'mcp':'Model Context Protocol (MCP)','skill-files':'Skill file','agent-harness':'Agent harness','multi-agent-system':'Multi-agent system',
 'tool-route':'Routes into an agent','text-route':'Routes into an agent','encoder-route':'Routes into an agent','verifier-route':'Routes into an agent',
 'decipherment-questions':'Decipherment analogy','orchestration-boundary':'Orchestration boundary','cnn':'Convolutional neural network',
 'simple-baselines':'Baseline','circular-annotation':'Circularity','systematic-variation':'Systematic variation','scaling-laws':'Scaling laws',
 'boundary-statement':'Boundary statement','self-driving-lab':'Self-driving laboratory','model-registry':'Model registry'
};
/* themes for concepts with no S1 counterpart */
const GROUP_FOR={'knowledge-extraction':0,'compression-vs-composability':0,'correlation-vs-causation':0,'regulatory-dna':0,'tf-binding-motif':0,
 'supervised-learning':1,'bulk-rna-seq':2,'spatial-transcriptomics':2,'sampling-bias':4,'four-layers':4,'reinforcement-learning':5,
 'stages-of-biological-science':6,'adaptive-radiation':6,'shared-literacy':6};
const GN=[...new Set(G.map(g=>g.g))];
const ids=Object.keys(T);
const un=[];ids.forEach(id=>{ if(!MAP[id] && !(id in GROUP_FOR)) un.push(id); });
if(un.length){ console.error('UNMAPPED',un, ids.filter(i=>/layers|sampling/.test(i))); process.exit(1); }
Object.values(MAP).forEach(n=>{ if(!gnames.has(n)) throw new Error('no S1 term '+n); });
const cslug={}, cx={}, extra=[];
const secOK=s=>s==='Abstract'?'1':s;
ids.forEach(id=>{
  const t=T[id];
  let name=MAP[id];
  if(!name){ name=t.name; extra.push({g:GN[GROUP_FOR[id]],t:name,d:t.def,e:'',s:[secOK(t.section)],cx:[id]}); }
  cslug[id]=slug(name);
  const ex=(t.examples||[]).map(x=>E[x]).filter(Boolean).map(e=>({dir:e.direction,h:e.text_html,f:e.finding||'',de:e.design_element||'',o:e.origin_claim,os:e.origin_section}));
  cx[id]={sc:secOK(t.section),n:t.name,d:t.def,de:t.design_element||'',b:t.home_beat||'',k:t.kind,ev:!!t.evidence_only,ex};
});
const mapped={}; Object.entries(MAP).forEach(([id,n])=>(mapped[n]=mapped[n]||[]).push(id));
const slugs=[...G.map(g=>slug(g.t)),...extra.map(e=>slug(e.t))];
if(new Set(slugs).size!==slugs.length) throw new Error('slug collision');
const block=`/*CX-START (generated by build/merge_glossary.js)*/\nconst CX = ${JSON.stringify(cx)};\nconst CX_MAP = ${JSON.stringify(mapped)};\nGLOSS.forEach(r=>{ if(CX_MAP[r.t]) r.cx=CX_MAP[r.t]; });\nGLOSS.push(...${JSON.stringify(extra)});\n/*CX-END*/\n`;
html=html.replace(/\/\*CX-START[\s\S]*?\/\*CX-END\*\/\n/,'');
html=html.replace(/(const GLOSS = \[.*\];\n)/,(m)=>m+block);
fs.writeFileSync('resource.html',html);
fs.writeFileSync('glossary-map.js','/* concept id -> glossary slug; generated by build/merge_glossary.js */\nconst CONCEPT_SLUG = '+JSON.stringify(cslug)+';\n');
console.log('concepts',ids.length,'extra entries',extra.length,'total glossary',G.length+extra.length);
